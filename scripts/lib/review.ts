import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

export type OpenItemKind = 'question' | 'decision-pending' | 'known-issue-review' | 'marker';

export interface OpenItem {
  id: string;
  kind: OpenItemKind;
  blocking: boolean;
  summary: string;
  source: string;
}

export interface ReviewResult {
  project: string;
  items: OpenItem[];
  overrideAllowed: boolean;
}

interface Block {
  id: string;
  summary: string;
  body: string;
}

function splitBlocks(markdown: string): Block[] {
  const lines = markdown.split('\n');
  const blocks: Block[] = [];
  let current: { id: string; summary: string; bodyLines: string[] } | null = null;

  for (const line of lines) {
    const heading = /^###\s+(.+)$/.exec(line);
    if (heading) {
      if (current) {
        blocks.push({ id: current.id, summary: current.summary, body: current.bodyLines.join('\n') });
      }
      const text = heading[1].trim();
      const colon = text.indexOf(':');
      const id = (colon >= 0 ? text.slice(0, colon) : text).trim();
      const summary = (colon >= 0 ? text.slice(colon + 1) : '').trim();
      current = { id, summary, bodyLines: [] };
    } else if (current) {
      current.bodyLines.push(line);
    }
  }
  if (current) {
    blocks.push({ id: current.id, summary: current.summary, body: current.bodyLines.join('\n') });
  }
  return blocks;
}

function field(body: string, name: string): string | undefined {
  const re = new RegExp(`^[\\s-]*\\*{0,2}${name}\\*{0,2}\\s*:\\s*(.+)$`, 'im');
  const match = re.exec(body);
  return match ? match[1].trim().replace(/\*/g, '') : undefined;
}

export function parseQuestions(markdown: string, sourceFile: string): OpenItem[] {
  return splitBlocks(markdown)
    .filter((block) => (field(block.body, 'Status') ?? '').toLowerCase() === 'open')
    .map((block) => ({
      id: block.id,
      kind: 'question' as const,
      blocking: (field(block.body, 'Blocking') ?? '').toLowerCase() === 'yes',
      summary: block.summary,
      source: sourceFile
    }));
}

export function parseKnownIssues(markdown: string, sourceFile: string): OpenItem[] {
  return splitBlocks(markdown)
    .filter((block) => (field(block.body, 'Human review') ?? '').toLowerCase() === 'pending')
    .map((block) => ({
      id: block.id,
      kind: 'known-issue-review' as const,
      blocking: false,
      summary: block.summary,
      source: sourceFile
    }));
}

export function parseOverride(markdown: string): boolean {
  const match = /allow proceed with open questions:\**\s*(yes|no)/i.exec(markdown);
  return match ? match[1].toLowerCase() === 'yes' : false;
}

export function isBlocked(result: ReviewResult): boolean {
  return result.items.some((item) => item.blocking) && !result.overrideAllowed;
}

export function reviewProject(projectDir: string): ReviewResult {
  const project = path.basename(projectDir);
  const items: OpenItem[] = [];

  const questionsPath = path.join(projectDir, 'questions.md');
  if (existsSync(questionsPath)) {
    items.push(...parseQuestions(readFileSync(questionsPath, 'utf8'), 'questions.md'));
  }

  const knownIssuesPath = path.join(projectDir, 'known-issues.md');
  if (existsSync(knownIssuesPath)) {
    items.push(...parseKnownIssues(readFileSync(knownIssuesPath, 'utf8'), 'known-issues.md'));
  }

  const decisionsPath = path.join(projectDir, 'decisions.md');
  const overrideAllowed = existsSync(decisionsPath)
    ? parseOverride(readFileSync(decisionsPath, 'utf8'))
    : false;

  return { project, items, overrideAllowed };
}

function renderItemLines(items: OpenItem[]): string {
  if (items.length === 0) {
    return '_None._';
  }
  return items
    .map((item) => `- **${item.id}** ${item.summary} (\`${item.source}\`)`)
    .join('\n');
}

export function renderOpenItems(result: ReviewResult): string {
  const blocking = result.items.filter((item) => item.blocking);
  const nonBlocking = result.items.filter((item) => !item.blocking);
  const blocked = isBlocked(result);

  const header = result.items.length > 0
    ? `> ACTION REQUIRED: ${result.items.length} item(s) need a human decision${
        blocked ? ' (execution work is gated)' : result.overrideAllowed ? ' (override active)' : ''
      }.`
    : '> No open items. Nothing awaits a human decision.';

  return `# Open Items — ${result.project}

${header}

Generated by \`qa:review\`. Do not hand-edit; resolve items in their source files.

## Blocking (${blocking.length})

${renderItemLines(blocking)}

## Non-blocking (${nonBlocking.length})

${renderItemLines(nonBlocking)}
`;
}
